"""
UiPath AI Export - Prompts

Prompt templates paired with the purposes defined in ai_export.py (PURPOSES dict -
purpose keys must match).

Project-scope purposes: "debug" (despite the key name, this is now an *architecture*
review - see ARCHITECTURE_DEBUG_PROMPT_TASK below for why), "business_doc".
File-scope purposes: "file_summary", "file_debug" - two separate prompts (replacing
the old single "file_deep_dive") so a reader who just wants to understand the file
isn't handed the same prompt as someone hunting a specific bug in it. ai_export.py's
PURPOSES dict (and whatever builds AI_FILE_EXPORTS) needs a matching entry for each
of these four keys.

Each prompt is built from two parts, concatenated by build_prompt():
1. SCHEMA_EXPLAINER - a single shared explanation of the JSON shape ai_export.py
   produces. Written once here rather than per-purpose, since the shape itself
   doesn't change between purposes (only which tags/fields survive the trim) - a
   duplicated explanation per prompt would just be more tokens saying the same thing.
   This is itself part of the token-saving strategy discussed earlier: an AI that's
   told up front what `decl_id`-less refs, `key_arguments` vs `assignments`, and
   branch `steps` mean doesn't have to spend its own reasoning inferring the schema
   from examples.
2. A purpose-specific task instruction - what to actually do with the data once the
   AI understands the shape.

The final text sent to an AI chat is: PROMPT + the ai_export.py output, concatenated
by the UI layer (the "Copy" button in the project_map.html modal) - this module only
builds the instructional prefix, not the combined payload. Keeping that concatenation
in the UI layer (rather than doing it here) means the same prompt text can be shown
to the user for review before copying, separately from the data block.
"""

SCHEMA_EXPLAINER = """\
You will receive a structured export of a UiPath RPA project, generated by a custom \
scanner tool (not raw XAML). Here is how to read it:

- The export is organized per workflow file (one JSON block per .xaml file), each \
under a "### <relative_path>" heading.
- "arguments": the file's public parameters (name, direction In/Out/In-Out, type) - \
this is the file's "signature", what it expects to receive and return.
- "variables": internal variables declared in the file, with their name, type, and \
the container (scope) they're declared in.
- "invokes": other workflow files this file calls (InvokeWorkflowFile), including \
"argument_bindings" - which expression is passed to which argument of the called \
file. This is the actual cross-file data flow, not just a call graph.
- "invoked_by": which other files call this one (the reverse of "invokes").
- "activity_flow": the ordered tree of activities in the file, structured as it \
actually appears (not flattened). Two node shapes appear in this tree:
  - {"type": "activity", "tag": <UiPath activity type>, "name": <display name>, ...}: \
a single step. May include "assignments" (To/Value pairs, for Assign activities), \
"key_arguments" or "arguments" (the activity's most relevant parameter values), an \
"annotation" (a developer-written comment on that specific activity - treat these as \
high-trust hints about intent), and "children" (nested activities, e.g. inside a \
Sequence).
  - {"type": "branch", "kind": "if"/"switch"/"trycatch", "condition": ..., \
"branches": [{"label": ..., "condition": ..., "steps": [...]}]}: a control-flow \
split. Each branch's "label" tells you which path it is (e.g. "Then", "Else If", \
"Case X", "Try", "Catch (SomeException)", "Finally"), and "steps" is that branch's \
own activity list, in the same two-shape format.
- Expression text (e.g. inside "value", "condition", "assignments") is UiPath's \
VB-style expression syntax (e.g. "[myVariable]", "myVar.ToString()") - read it as \
code, not as literal display text.
"""


# Appended only to the single-file export prompt (see FILE_DEEP_DIVE_PROMPT_TASK
# below), since it explains a section (Neighboring files) that only ever appears in
# a single-file export - the whole-project export has no need for it, as every
# file's own full section is already present elsewhere in that same export.
FILE_SCHEMA_ADDENDUM = """\
You are receiving a **single workflow file** from a larger UiPath project, not the \
whole project - do not assume you are seeing every file. After the file's own \
"### <relative_path>" section, a "## Neighboring files (signatures only, not full \
flow)" section lists the files it calls and the files that call it, each shown only \
as "<path>: <arguments>" (its public In/Out contract) - not that neighbor's internal \
logic. Use these to understand what data crosses each call boundary, but do not \
speculate about a neighbor's internal implementation beyond what its signature tells \
you.
"""


ARCHITECTURE_DEBUG_PROMPT_TASK = """\
Your task: review this UiPath project as a senior RPA architect auditing its \
*structure* - not a line-by-line bug hunt inside individual files, and not a \
functional summary. Judge whether the project is put together well.

If an "## Additional context" section appears below (before the project's export \
data), the user has flagged a specific area of concern or suspicion - e.g. a \
particular file, folder, or process they suspect is fragile or badly structured. \
Treat it as a lead to prioritize, but still review the whole project as described \
below rather than looking only at what was mentioned - a suspicion about one area \
doesn't mean other areas are exempt. If no such section is present, review the \
project with no particular starting point.

Concretely, look for:
- Control-flow shape: files that mix orchestration and detailed implementation \
instead of delegating cleanly, overly deep nesting of branches, or a "god file" that \
does too much and should be split into smaller invoked workflows.
- Dependency structure: the invokes/invoked_by graph across files - circular or \
redundant invocation chains, a low-level file invoked from many unrelated places \
(signals it should be a shared library step, or that responsibilities aren't well \
separated), or a dynamic (non-literal) InvokeWorkflowFile path that breaks static \
traceability of the graph.
- Contract consistency across boundaries: argument direction (In/Out/In-Out) that \
doesn't match how the callee actually uses it based on argument_bindings, or \
inconsistent naming/typing for what is conceptually the same piece of data as it \
crosses multiple file boundaries.
- Error-handling as a project-wide pattern: is exception handling applied \
consistently across files that do similar risky work (UI automation, file/Excel/API \
calls), or does it exist in some files and not others with no apparent reason - \
inconsistency here is itself an architectural finding, distinct from a single \
missing TryCatch in one file.
- Retry/logging as a project-wide pattern: same idea - is there a consistent \
strategy for retrying transient failures and logging for diagnosability, or is it \
ad hoc per file.

For each finding, cite the specific files (and, where relevant, activities) \
involved, explain concretely why it's an architectural weakness rather than a local \
one, and suggest how you'd restructure it. Prioritize findings by how much they'd \
affect the project's maintainability or reliability at scale, not by how many you \
can list. This is not the place to flag a single isolated bug inside one file's \
internal logic - if you find one, mention it only if it's evidence of the broader \
pattern.

Only report a finding you can point to concretely in the data above - do not \
manufacture a weak or speculative one just to have something to say. If the \
project's structure is genuinely sound (clean delegation between files, consistent \
error-handling/retry/logging patterns, no problematic dependency shapes), say that \
plainly and name what's done well, rather than inventing an architectural weakness \
that isn't actually there. "No significant architectural issues found" is a valid \
and useful conclusion when it's true.
"""


BUSINESS_DOC_PROMPT_TASK = """\
Your task: write a functional/business specification document explaining what this \
UiPath project does, for a reader who is NOT a developer (e.g. a business \
stakeholder, process owner, or new team member who needs to understand the process \
without reading code).

If an "## Additional context" section appears below (before the project's export \
data), the user has told you what to focus on or who the document is for - e.g. a \
specific process area to expand on, or a particular audience (finance, compliance, \
a new hire). Follow that emphasis, but still produce a complete document using the \
structure below rather than dropping sections it doesn't mention. If no such \
section is present, write for the general non-developer reader described above.

Throughout the entire document, translate every technical identifier into plain \
language - never write a raw argument name, variable name, activity tag, file path, \
or expression exactly as it appears in the export. Describe what it represents \
instead (e.g. "the case reference it receives," not the argument name itself; "the \
configured file-share path," not the literal config key). This applies to every \
section below, not just the ones about process steps - a parameter list or a \
config summary is exactly where identifiers tend to leak in verbatim, so translate \
them there as deliberately as anywhere else.

Structure the document as:
1. **Process overview** - one paragraph: what business process does this automation \
perform, start to end, in plain language.
2. **Trigger & inputs** - what starts this process and what information it needs, \
described in plain business terms (e.g. "the case reference to process" or "the \
customer's account number") rather than by the entry-point file's literal argument \
names.
3. **Main process steps** - walk through the actual business logic in order (what \
decisions are made and why, referencing branch conditions in plain language, not as \
code expressions), organized by the workflow file structure. Skip low-level \
technical steps (e.g. individual UI clicks/keystrokes) unless they are the actual \
point of a step - describe what is accomplished, not how each activity is \
configured.
4. **Key decision points** - call out each meaningful branch (If/Switch) in the \
process and explain, in business terms, what determines which path is taken.
5. **Dependencies & configuration** - if project metadata or config values are \
included, summarize in plain terms what external systems, files, or settings this \
process depends on - describe what each one is for, not its raw key or path.

Use developer-written annotations wherever present as your primary source of intent - \
they represent what the developer explicitly wanted future readers to know. Do not \
speculate about business rules not evidenced in the data; if a step's business \
purpose isn't clear from names/annotations, say so rather than inventing a rationale.
"""


