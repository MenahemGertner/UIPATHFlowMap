FILE_DEBUG_PROMPT_TASK = """\
Your task: act as a developer investigating a specific problem in this ONE workflow \
file - a targeted diagnosis, not a general code review and not a project-wide check.

If a "## Reported issue" section appears below (before the file's export data), it \
describes the symptom the user is actually seeing. Treat it as the primary lead: \
trace the specific arguments, variables, and activities that could plausibly produce \
that symptom, and identify the most likely root cause(s) - cite the exact activity, \
argument, or variable responsible, and explain the mechanism (why the flow produces \
that symptom), not just where it might be. If nothing in the data actually explains \
the reported symptom, say so directly rather than inventing a plausible-sounding but \
unsupported cause - note what you checked and ruled out, and what additional \
information (e.g. runtime logs, the actual input values used) would be needed to go \
further.

If no "## Reported issue" section is present, perform a general debugging pass over \
this file instead, looking for the kinds of concrete defects that actually break a \
single file at runtime:
- Argument direction mismatches: an argument declared In but whose value the flow \
treats as something it should be writing back, an Out argument that is never \
assigned on some execution path (e.g. inside only one branch of an If, or not in a \
Catch), or an In/Out argument that's read before it's ever been given a value on \
some path.
- Variables read before being assigned on some path, assigned in one branch but \
relied upon after a branch that doesn't set it, or shadowing/reuse that could carry \
a stale value across an unrelated part of the flow.
- Unsafe assumptions in expressions: collection/array access without a bounds or \
null check, division that could hit zero, string operations on a value that might be \
empty or Nothing.
- Exception handling gaps around this file's own risky activities (UI automation, \
file/Excel/API calls), or a Catch broad enough to be swallowing the actual error \
instead of surfacing it.
- A dynamic (non-literal) InvokeWorkflowFile path or argument binding whose actual \
target/value can't be confirmed from this data alone - flag it as unverifiable \
rather than guessing what it resolves to.

If you don't find any real instance of the issues above, say so plainly rather than \
manufacturing a marginal or speculative one just to produce output - a file with no \
notable defects is a valid and useful finding, not an incomplete answer.

Either way, cite the specific activity (by name/tag), argument, or variable involved \
in each point you raise, and state your confidence - some causes will be certain \
from the data shown, others only plausible candidates worth checking.
"""


PROMPTS: dict[str, str] = {
    "debug": SCHEMA_EXPLAINER + "\n" + ARCHITECTURE_DEBUG_PROMPT_TASK,
    "business_doc": SCHEMA_EXPLAINER + "\n" + BUSINESS_DOC_PROMPT_TASK,
    "file_summary": SCHEMA_EXPLAINER + "\n" + FILE_SCHEMA_ADDENDUM + "\n" + FILE_SUMMARY_PROMPT_TASK,
    "file_debug": SCHEMA_EXPLAINER + "\n" + FILE_SCHEMA_ADDENDUM + "\n" + FILE_DEBUG_PROMPT_TASK,
}


def build_prompt(purpose_key: str) -> str:
    """
    Returns the instructional prefix for the given purpose. Raises KeyError on an
    unregistered purpose key, same contract as ai_export.build_ai_export - a caller
    passing an unknown key is a wiring bug (the UI is expected to only offer keys
    that exist in both PROMPTS here and PURPOSES in ai_export.py), not user input to
    validate defensively.
    """
    return PROMPTS[purpose_key]


def build_full_payload(purpose_key: str, export_text: str, user_notes: str = "") -> str:
    """
    Convenience combiner: prompt + a blank line + the ai_export.py output, ready to
    paste as-is into an AI chat. The UI layer is free to do this concatenation itself
    instead (e.g. to show the prompt and data as separate preview panes before
    copying) - this exists for the common single-string case (e.g. a CLI test run).

    user_notes is optional free text from the user, inserted as a marker section
    right before the export data - every purpose explains in its own task
    instruction how it's used, and all of them fall back to their default behavior
    when it's left blank. The marker's header depends on what the note actually
    represents for that purpose: "file_debug" frames it as a reported symptom to
    diagnose ("## Reported issue"); the other three ("debug", "business_doc",
    "file_summary") frame it as context or a focus/audience to prioritize, since
    none of them are diagnosing a single bug ("## Additional context").
    """
    if not user_notes.strip():
        return f"{build_prompt(purpose_key)}\n\n---\n\n{export_text}"
    header = "## Reported issue" if purpose_key == "file_debug" else "## Additional context"
    return f"{build_prompt(purpose_key)}\n\n{header}\n{user_notes.strip()}\n\n---\n\n{export_text}"


